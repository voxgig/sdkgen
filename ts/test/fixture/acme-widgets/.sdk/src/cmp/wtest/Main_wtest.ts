// `wtest`'s Main — the entry point sdkgen's neutral `Main` dispatches to by
// the convention `cmp/<t>/Main_<t>`.
//
// This is a FIXTURE target, so it emits the smallest thing that is still
// recognisably an SDK: a client file naming the API and listing its entities
// and active features. Every value it writes comes from the model, so a test
// can tell "the component ran" from "the component ran and saw the right
// model" — which is the distinction a fixture that emitted a constant could
// not support.

import {
  cmp, each, Folder, File, Content, entityCollection,
} from '@voxgig/sdkgen'


const Main = cmp(function Main(props: any) {
  const { model, target } = props

  const kit = model.main.kit
  const name = model.const?.name ?? model.name ?? ''

  // Active entities only, and by the same route every real target uses. The
  // unfiltered `entityCollection` is for class-name assignment; what an
  // emitter iterates has to respect `active: false`.
  const entities = each(entityCollection(model))
    .filter((e: any) => false !== e.active)
    .map((e: any) => e.name)
    .sort()

  const features = each(kit.feature)
    .filter((f: any) => f && false !== f.active)
    .map((f: any) => f.name)
    .sort()

  Folder({ name: 'src' }, () => {
    File({ name: 'client.' + target.ext }, () => {
      Content([
        '# ' + name + ' widget client',
        '# generated by @acme/sdkgen-widgets — do not edit',
        'sdk ' + name,
        'entities ' + entities.join(' '),
        'features ' + features.join(' '),
        '',
      ].join('\n'))
    })
  })
})


export {
  Main
}
