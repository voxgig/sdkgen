import { test, describe } from 'node:test'
import { deepStrictEqual, match, ok, strictEqual } from 'node:assert'
import Path from 'node:path'

import { Jostraca, Project } from 'jostraca'
import { memfs } from 'memfs'

import { SdkGen, Security, applyFacts } from '../dist/sdkgen.js'

import {
  publisherInfo,
  securityContact,
  authorInfo,
  keywords,
  nonAffiliation,
  pkgDescription,
} from '../dist/helpers/packageMeta.js'
import { ensureStdrep } from '../dist/helpers/stdrep.js'
import { SCAFFOLD, STAGE, layeredFs, makeLog, makeModel, makeRoot } from './generateharness'


async function security(repo?: any): Promise<string> {
  const { fs, vol } = memfs({})
  const log: any = { info() {}, debug() {}, warn() {}, error() {}, trace() {}, fatal() {}, child() { return log } }
  await Jostraca().generate(
    { fs: () => fs, folder: '/x', model: model(undefined, repo ? { repo } : {}), log },
    () => Project({ folder: 'p' }, () => Security({})),
  )
  return String(vol.toJSON()['/x/p/SECURITY.md'])
}


// The generated files that call the SDK unofficial or disclaim an affiliation.
async function disclaiming(publisher: string): Promise<string[]> {
  const { fs, vol } = memfs({})
  const cwd = process.cwd()
  process.chdir(SCAFFOLD)
  try {
    await SdkGen({ fs: layeredFs(fs), folder: STAGE, root: '', pino: makeLog([]) })
      .generate({ model: makeModel(['ts', 'py'], undefined, 'main: kit: publisher: ' + publisher), root: makeRoot() })
  }
  finally {
    process.chdir(cwd)
  }
  return Object.entries(vol.toJSON() as Record<string, string | null>)
    .map(([path, text]) => [Path.relative(STAGE, path).split(Path.sep).join('/'), String(text)])
    .filter(([rel, text]) => !rel.includes('.jostraca/') && !rel.startsWith('.sdk/log/') &&
      /unofficial|affiliated/i.test(text))
    .map(([rel]) => rel)
    .sort()
}


function model(publisher?: any, rest?: any): any {
  return applyFacts({
    name: 'demo',
    main: { kit: { ...(publisher ? { publisher } : {}), ...(rest || {}) } },
  })
}


describe('publisher', () => {

  test('an undeclared or empty publisher is Voxgig, with its url and contact', () => {
    const voxgig = {
      name: 'Voxgig', url: 'https://voxgig.com', security: 'security@voxgig.com', official: false,
    }
    deepStrictEqual(publisherInfo(model()), voxgig)
    deepStrictEqual(publisherInfo(model({ name: '', url: '', security: '' })), voxgig)
    strictEqual(securityContact(model()), 'to security@voxgig.com')
  })

  test('another publisher takes none of Voxgig\'s url or contact', () => {
    const acme = model({ name: 'Acme' })
    deepStrictEqual(publisherInfo(acme), { name: 'Acme', url: '', security: '', official: false })
    strictEqual(securityContact(acme), 'privately to Acme')
    strictEqual(securityContact(model({ name: 'Acme', url: 'https://acme.example' })),
      'privately to Acme (https://acme.example)')
    strictEqual(securityContact(model({ name: 'Acme', security: 'sec@acme.example' })),
      'to sec@acme.example')
  })

  test('the publisher is the default author, and a declared author wins', () => {
    deepStrictEqual(authorInfo(model({ name: 'Acme', url: 'https://acme.example' }), 'ts'),
      { name: 'Acme', url: 'https://acme.example' })

    const declared = model({ name: 'Acme', url: 'https://acme.example' },
      { author: { name: 'Ada', url: '' } })
    deepStrictEqual(authorInfo(declared, 'ts'), { name: 'Ada', url: '' })

    deepStrictEqual(authorInfo(model(), 'ts'),
      { name: 'Voxgig', url: 'https://voxgig.com' })
  })

  test('only Voxgig is credited in keywords and the notice', () => {
    strictEqual(keywords(model())[0], 'voxgig')
    strictEqual(keywords(model({ name: 'Acme' })).includes('voxgig'), false)
    strictEqual(nonAffiliation(model({ name: 'Acme' })).includes('generated by Acme with'), true)
  })

  test('a publisher that owns the API disclaims no affiliation', () => {
    const ts = { target: { ts: { name: 'ts', title: 'TypeScript' } } }
    const own = model({ name: 'Acme', official: true }, ts)
    for (const text of [nonAffiliation(own), pkgDescription(own, 'ts')]) {
      strictEqual(/unofficial|affiliated/i.test(text), false, text)
    }
    match(nonAffiliation(own), /generated by Acme with/)
    match(pkgDescription(model({ name: 'Acme' }, ts), 'ts'), /^Unofficial .* Not affiliated/)
  })

  test('no file generated for a publisher that owns the API disclaims it', async () => {
    deepStrictEqual(await disclaiming("{ name: 'Acme', official: true }"), [])
    const unowned = await disclaiming("{ name: 'Acme' }")
    for (const file of ['NOTICE', 'README.md', 'SECURITY.md', 'ts/package.json', 'py/pyproject.toml']) {
      ok(unowned.includes(file), file + ' disclaims an affiliation unless the publisher owns the API')
    }
  })

  test('the template placeholder is the publisher name', () => {
    strictEqual(ensureStdrep({ model: model({ name: 'Acme' }) }).PROJECTPUBLISHER, 'Acme')
    strictEqual(ensureStdrep({ model: model() }).PROJECTPUBLISHER, 'Voxgig')
  })

  test('SECURITY.md names the host the issues live on', async () => {
    match(await security(), /Do not open public GitHub issues for suspected/)
    const gitlab = await security({ host: 'gitlab.com', path: 'acme/demo-sdk' })
    match(gitlab, /Do not open public GitLab issues for suspected/)
    match(gitlab, /gitlab\.com\/acme\/demo-sdk\/-\/issues/)
    match(await security({ host: 'git.example.com', path: 'acme/demo-sdk' }),
      /Do not open public issues on git\.example\.com for suspected/)
  })
})
