import { Content, File, each } from 'jostraca'
import { cmp } from '../helpers/component'
import { fact } from '../helpers/facts'
import { documentOrder, surfaceOf } from '../helpers/surface'
import { seriesList } from '../helpers/text'
import { KIT, getModelPath } from '../types'

import {
  apiName, isDefaultPublisher, publisherInfo, registryLabel, registryName, repoInfo,
  securityContact,
} from '../helpers/packageMeta'


// Where the SDK packages are published: each registry, then the Go module,
// then the git tags a port with no registry releases by.
function publishedTo(model: any): string[] {
  const sdks = documentOrder(model,
    each(getModelPath(model, `main.${KIT}.target`, { required: false }) || {})
      .filter((t: any) => false !== t.active && 'sdk' === surfaceOf(t)))

  const registries = sdks.filter((t: any) => 'go' !== fact(t, 'origin'))
    .map((t: any) => registryName(model, t.name))

  return [
    ...new Set(registries.filter((name: string) => '' !== name).map(registryLabel)),
    ...(sdks.some((t: any) => 'go' === fact(t, 'origin')) ? ['the Go module'] : []),
    ...(registries.includes('') ? ['git tags'] : []),
  ]
}


const Security = cmp(function Security(props: any) {
  const { ctx$ } = props
  const { model } = ctx$

  const { issuesUrl, host, hostName } = repoInfo(model)
  const publicIssues = hostName === host ? `public issues on ${host}` : `public ${hostName} issues`
  const publisher = publisherInfo(model)

  // Voxgig's own response commitment, which another publisher has not made.
  const promise = isDefaultPublisher(model) ?
    ' We aim to\nacknowledge reports within 3 business days.' : ''

  const places = publishedTo(model)

  File({ name: 'SECURITY.md' }, () => {
    Content(`# Security Policy

## Reporting a vulnerability

Please report security issues ${securityContact(model)}.

Do not open ${publicIssues} for suspected vulnerabilities.${promise}

For non-security bugs, use the issue tracker: ${issuesUrl}

## Scope

This policy applies to the generated ${publisher.name} SDK packages published from this
repository${0 === places.length ? '' : ' (' + seriesList(places) + ')'}.

This is an unofficial SDK for the ${apiName(model)} public API, generated by
${publisher.name}. It is not affiliated with, endorsed by, or sponsored by the upstream
API provider.
`)
  })
})


export {
  Security
}
