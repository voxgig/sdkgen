// Stage the shipped scaffold as a MINIMAL CONSUMER PROJECT so that
// test/generate.test.ts can run the per-language components for real.
//
// Why this is needed: `requirePath` resolves a component with
// `require(<folder>/.sdk/dist/cmp/<lang>/<Cmp>_<lang>)` — a real Node require
// against the real filesystem, not the memfs volume generation writes into.
// The components also read sibling files off disk relative to their own
// __dirname (`../../../src/cmp/<lang>/fragment/...`, `../../README.md`). So a
// generation test needs a directory laid out exactly like a consumer's `.sdk`:
//
//   dist-test-scaffold/
//     node_modules/@voxgig/sdkgen   -> re-export of this package's own dist
//     .sdk/src/cmp/<lang>/...       -> copy (fragments + docs read at runtime)
//     .sdk/model/target|feature/... -> copy (the test writes its own sdk.aontu
//                                     alongside and unifies against these, so
//                                     the fixture inherits REAL target defaults
//                                     instead of restating them)
//     .sdk/dist/cmp/<lang>/...      -> compiled JS (tsconfig.scaffold-emit.json)
//
// This script does the copies and the self-link; tsc does the compile. Output
// is gitignored and rebuilt by `npm run build`.

const Fs = require('node:fs')
const Path = require('node:path')


const TS = Path.resolve(__dirname, '..')
const SRC = Path.join(TS, 'project', '.sdk', 'src')
const MODEL = Path.join(TS, 'project', '.sdk', 'model')
const STAGE = Path.join(TS, 'dist-test-scaffold')
const STAGE_SRC = Path.join(STAGE, '.sdk', 'src')
const STAGE_MODEL = Path.join(STAGE, '.sdk', 'model')


function main() {
  if (!Fs.existsSync(SRC)) {
    throw new Error('scaffold source not found: ' + SRC)
  }

  // Full rebuild: a component deleted from the scaffold must not survive here
  // and keep a stale test passing.
  Fs.rmSync(STAGE, { recursive: true, force: true })

  Fs.mkdirSync(Path.dirname(STAGE_SRC), { recursive: true })
  Fs.cpSync(SRC, STAGE_SRC, { recursive: true })
  Fs.cpSync(MODEL, STAGE_MODEL, { recursive: true })

  // The components `require('@voxgig/sdkgen')` the way a consumer does. Inside
  // this repo that name has no node_modules entry (this IS the package), so
  // provide one. A directory with a re-export beats a symlink: symlinks need
  // elevation on the Windows leg of the CI matrix.
  const link = Path.join(STAGE, 'node_modules', '@voxgig', 'sdkgen')
  Fs.mkdirSync(link, { recursive: true })
  Fs.writeFileSync(
    Path.join(link, 'package.json'),
    JSON.stringify({ name: '@voxgig/sdkgen', version: '0.0.0', main: 'index.js' }, null, 2) + '\n')
  Fs.writeFileSync(
    Path.join(link, 'index.js'),
    '// Generated by build/scaffold-stage.js — do not edit.\n' +
    "module.exports = require('../../../../dist/sdkgen.js')\n")

  console.log('staged scaffold -> ' + Path.relative(TS, STAGE))
}


main()
